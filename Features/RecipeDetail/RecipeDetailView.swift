                withAnimation(.easeInOut(duration: 0.2)) { isCooking = true }
            } else {
                markAsCooked()
                dismiss()
            }
        }
    }

    // MARK: - Pantry Match

    private struct MatchedIngredient: Identifiable {
        var id: UUID { recipeIngredient.id }
        let recipeIngredient: RecipeIngredient
        let pantryIngredient: Ingredient
        let isSufficient: Bool?
    }

    /// Keyed by recipe-ingredient id so `ingredientRow` can look up a match in O(1) instead of
    /// re-scanning the whole pantry-match list once per row.
    private var pantryMatchedIngredients: [UUID: MatchedIngredient] {
        Dictionary(uniqueKeysWithValues: recipe.ingredientsUsed.compactMap { recipeIngredient -> (UUID, MatchedIngredient)? in
            guard let pantry = PantryMatcher.find(for: recipeIngredient.name, in: pantryStore.ingredients) else { return nil }
            let match = MatchedIngredient(
                recipeIngredient: recipeIngredient,
                pantryIngredient: pantry,
                isSufficient: QuantityConverter.isSufficient(
                    have: pantry.totalAmount,
                    need: recipeIngredient.quantity
                )
            )
            return (recipeIngredient.id, match)
        })
    }

    private func dotColor(for sufficient: Bool?) -> Color {
        sufficient == false ? Sourdough.Ramp.honey500 : Sourdough.Ramp.sage500
    }

    private func markAsCooked() {
        for match in pantryMatchedIngredients.values {
            let pantry = match.pantryIngredient
            guard let parsedPantry = QuantityConverter.parse(pantry.totalAmount ?? ""),
                  let parsedNeed = QuantityConverter.parse(match.recipeIngredient.quantity),
                  parsedPantry.unit.category == parsedNeed.unit.category else {
                continue
            }

            let remaining = parsedPantry.toBase() - parsedNeed.toBase()
            if remaining <= 0 {
                pantryStore.useIngredient(id: pantry.id, newAmount: nil)
            } else {
                let newValue = parsedPantry.unit.fromBase(remaining)
                let newAmountStr = "\(QuantityConverter.formatQuantity(newValue)) \(parsedPantry.unit.label)"
                pantryStore.useIngredient(id: pantry.id, newAmount: newAmountStr)
            }
        }
    }

    // MARK: - PDF

    @MainActor
    private func generatePDF() -> URL? {
        let printView = RecipePrintView(recipe: recipe)
            .environment(\.colorScheme, .light)

        let renderer = ImageRenderer(content: printView)
        renderer.proposedSize = .init(width: 612, height: nil)

        let url = FileManager.default.temporaryDirectory.appendingPathComponent("\(recipe.title).pdf")

        renderer.render { size, renderInContext in
            var box = CGRect(origin: .zero, size: size)
            guard let context = CGContext(url as CFURL, mediaBox: &box, nil) else { return }
            context.beginPDFPage(nil)
            renderInContext(context)
            context.endPDFPage()
            context.closePDF()
        }

        return FileManager.default.fileExists(atPath: url.path) ? url : nil
    }
